-- =====================================================================
--  سلّم التقديرات الافتراضي
--
--  كان الجدول فارغاً، فتصدر الشهادات بلا تقدير وتبقى «نسبة النجاح» في
--  التقارير بلا قيمة. هذه نطاقات مبدئية قابلة للتعديل بالكامل من
--  صفحة «أساس التحكيم ← سلّم التقديرات»، ولا تُدرج إن كان الجدول غير فارغ.
-- =====================================================================
insert into public.grade_scales (name, min_score, max_score, is_passing)
select v.name, v.min_score, v.max_score, v.is_passing
from (values
  ('ممتاز',      90.00, 100.00, true),
  ('جيد جداً',   80.00,  89.99, true),
  ('جيد',        70.00,  79.99, true),
  ('مقبول',      60.00,  69.99, true),
  ('راسب',        0.00,  59.99, false)
) as v(name, min_score, max_score, is_passing)
where not exists (select 1 from public.grade_scales);
